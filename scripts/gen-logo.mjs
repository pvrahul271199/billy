// Generates the Billy logo: outlines the wordmark, writes public/logo.svg,
// theme/logo.ts (path for <Logo />), favicon.svg and the PNG app icons.
//   node scripts/gen-logo.mjs            build everything
// Re-run after changing FONT / BG below. `npm run icons` is the same command.
import opentype from "opentype.js";
import sharp from "sharp";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const BG = "#1E1B4B"; // theme/tokens.ts `ink`
const TEXT = "Billy";
const FONT = "node_modules/@fontsource/bricolage-grotesque/files/bricolage-grotesque-latin-600-normal.woff"; // Bricolage Grotesque SemiBold, same as Stash and the homepage
const WIDTH = 72; // wordmark width as % of the 100-unit tile
const TRACK = -0.045; // same as the homepage wordmark (tracking-[-0.045em]) // extra letter-spacing, in em

function outline(fontFile, text, targetWidth, track = TRACK) {
  const font = (() => { const b = readFileSync(join(root, fontFile)); return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength)); })();
  const size = 100;
  const scale = size / font.unitsPerEm;
  let x = 0;
  const paths = [];
  const glyphs = [...text].map((c) => font.charToGlyph(c));
  glyphs.forEach((g, i) => {
    paths.push(g.getPath(x, 0, size));
    x += g.advanceWidth * scale + track * size;
    if (glyphs[i + 1]) x += font.getKerningValue(g, glyphs[i + 1]) * scale;
  });
  // Bounding box of the ink, then scale and centre on it (visual mass).
  let x1 = Infinity, y1 = Infinity, x2 = -Infinity, y2 = -Infinity;
  for (const p of paths) {
    const b = p.getBoundingBox();
    x1 = Math.min(x1, b.x1); y1 = Math.min(y1, b.y1);
    x2 = Math.max(x2, b.x2); y2 = Math.max(y2, b.y2);
  }
  const k = targetWidth / (x2 - x1);
  const dx = 50 - ((x1 + x2) / 2) * k;
  const dy = 50 - ((y1 + y2) / 2) * k;
  const f = (n) => Math.round(n * 100) / 100;
  let d = "";
  for (const p of paths) {
    for (const c of p.commands) {
      const t = (px, py) => `${f(px * k + dx)} ${f(py * k + dy)}`;
      if (c.type === "M") d += `M${t(c.x, c.y)}`;
      else if (c.type === "L") d += `L${t(c.x, c.y)}`;
      else if (c.type === "Q") d += `Q${t(c.x1, c.y1)} ${t(c.x, c.y)}`;
      else if (c.type === "C") d += `C${t(c.x1, c.y1)} ${t(c.x2, c.y2)} ${t(c.x, c.y)}`;
      else if (c.type === "Z") d += "Z";
    }
  }
  return d;
}

const tile = (d, { rounded = true, inset = 1, size = 512 } = {}) => {
  const s = inset;
  const g = s === 1 ? `<path d="${d}" fill="#fff"/>` : `<path transform="translate(50 50) scale(${s}) translate(-50 -50)" d="${d}" fill="#fff"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="${size}" height="${size}"><rect width="100" height="100"${rounded ? ' rx="22"' : ""} fill="${BG}"/>${g}</svg>`;
};

const d = outline(FONT, TEXT, WIDTH);

// public/logo.svg
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="512" height="512" role="img" aria-label="Billy"><rect width="100" height="100" rx="22" fill="${BG}"/><path d="${d}" fill="#fff"/></svg>\n`;
writeFileSync(join(root, "public/logo.svg"), svg);
writeFileSync(join(root, "public/favicon.svg"), svg);

// Single source for <Logo />
writeFileSync(
  join(root, "theme/logo.ts"),
  `// Generated by scripts/gen-logo.mjs. Do not edit by hand.\nexport const logoPath =\n  "${d}";\n`,
);

// PNG icons
mkdirSync(join(root, "public/icons"), { recursive: true });
const png = (name, markup, size) => sharp(Buffer.from(markup), { density: 300 }).resize(size, size).png().toFile(join(root, "public/icons", name));
await png("icon-192.png", tile(d), 192);
await png("icon-512.png", tile(d), 512);
await png("favicon-32.png", tile(d), 32);
await png("apple-touch-icon.png", tile(d, { rounded: false }), 180); // iOS rounds it
await png("maskable-512.png", tile(d, { rounded: false, inset: 0.72 }), 512);
console.log("done");
