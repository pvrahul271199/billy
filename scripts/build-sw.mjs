// Generates out/sw.js after `next build`: precaches every file in the static
// export so Billy works fully offline after the first visit.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = path.resolve("out");
const SKIP = new Set(["sw.js", ".DS_Store"]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => {
      const full = path.join(dir, e.name);
      return e.isDirectory() ? walk(full) : SKIP.has(e.name) ? [] : [full];
    }),
  );
  return files.flat();
}

const files = (await walk(OUT)).sort();
const hash = createHash("sha256");
const urls = [];
for (const file of files) {
  hash.update(file);
  hash.update(await readFile(file));
  const rel = "/" + path.relative(OUT, file).split(path.sep).join("/");
  // Pages are served at their directory URL ("/invoice/") with trailingSlash: true.
  if (rel.endsWith("/index.html")) urls.push(rel.slice(0, -"index.html".length));
  else urls.push(rel);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "billy-" + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("billy-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Cache first for everything on this origin. Query strings are ignored so
// "/preview/?id=..." is served by the cached "/preview/" page.
self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const cached = await cache.match(req, { ignoreSearch: true });
      if (cached) return cached;
      try {
        const res = await fetch(req);
        if (res.ok && res.type === "basic") cache.put(req, res.clone());
        return res;
      } catch (err) {
        if (req.mode === "navigate") {
          const fallback = await cache.match("/", { ignoreSearch: true });
          if (fallback) return fallback;
        }
        throw err;
      }
    }),
  );
});
`;

await writeFile(path.join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached, version ${version}`);
